# ---------------------------------------------------------------- hair


def bangs(c, tips, top=26, x0=15, x1=49, strand="H"):
    """Pointed locks hanging from the hairline: tips = list of tip rows across the forehead.
    Each lock gets a darker seam on one edge and every other lock a thin highlight, so the fringe
    reads as separate strands instead of one mass."""
    n = len(tips)
    step = (x1 - x0) / n
    for k, tip in enumerate(tips):
        xa, xb = x0 + k * step - 1.2, x0 + (k + 1) * step + 1.2
        cx = (xa + xb) / 2 + (0.8 if k < n / 2 else -0.8)
        c.poly([(xa, top), (xb, top), (cx, tip)], strand)
    for k, tip in enumerate(tips):
        xa = x0 + k * step
        cx = xa + step / 2 + (0.8 if k < n / 2 else -0.8)
        # seam on every other lock: a short dark line toward the tip, so strands separate softly
        if k % 2 == 1:
            for t in range(0, max(0, tip - top - 8)):
                f = (t + 5) / max(1, tip - top)
                x = int(xa + (cx - xa) * f * 0.9)
                if c.get(x, top + 5 + t) == strand:
                    c.set(x, top + 5 + t, "j")
        if k % 2 == 0 and tip - top > 7:
            for t in range(2, (tip - top) // 2):
                x = int(cx - 1 + t * 0.1)
                if c.get(x, top + t) == strand:
                    c.set(x, top + t, "h")


