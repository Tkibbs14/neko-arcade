#!/usr/bin/env python3
"""Procedural pixel painter for Neko Arcade dialogue busts (64x64, Prefect-Illustrious-style catgirls).

Writes art/bust.txt: a colour ramp shared by every character layer, then layers that the game stacks
in this order: outfit -> face -> eyes -> mouth -> hair -> ears -> accessory. Each layer is drawn with a
per-character ramp at run time, so one ear or face drawing serves every character.

Ramp slots (letters used in the sprites):
  k outline   s skin   d skin shadow   h/H/j hair or fur light/base/shadow   e eye dark   i iris
  w white (shine, ear fluff)   o/O/q outfit light/base/shadow   p pink (blush, inner ear)   m mouth   a accent
"""
import math, os

W = H = 64
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "art", "bust.txt")


class Canvas:
    def __init__(self, w=W, h=H):
        self.w, self.h = w, h
        self.g = [["."] * w for _ in range(h)]

    def get(self, x, y):
        return self.g[y][x] if 0 <= x < self.w and 0 <= y < self.h else "."

    def set(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = ch

    def poly(self, pts, ch, only_over=None):
        """Scanline-fill a polygon (list of (x, y) floats)."""
        ys = [p[1] for p in pts]
        for y in range(max(0, int(min(ys))), min(self.h, int(math.ceil(max(ys))) + 1)):
            yc = y + 0.5
            xs = []
            for i in range(len(pts)):
                (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % len(pts)]
                if (y0 <= yc < y1) or (y1 <= yc < y0):
                    xs.append(x0 + (yc - y0) * (x1 - x0) / (y1 - y0))
            xs.sort()
            for a, b in zip(xs[::2], xs[1::2]):
                for x in range(int(math.floor(a + 0.5)), int(math.floor(b + 0.5))):
                    if only_over is None or self.get(x, y) in only_over:
                        self.set(x, y, ch)

    def ellipse(self, cx, cy, rx, ry, ch, only_over=None, rows=None):
        for y in range(self.h):
            if rows and not (rows[0] <= y <= rows[1]):
                continue
            dy = (y + 0.5 - cy) / ry
            if abs(dy) > 1:
                continue
            hw = rx * math.sqrt(1 - dy * dy)
            for x in range(int(math.floor(cx - hw + 0.5)), int(math.floor(cx + hw + 0.5))):
                if only_over is None or self.get(x, y) in only_over:
                    self.set(x, y, ch)

    def outline(self, ch="k", inside=None, against=(".",)):
        """Turn every filled pixel that touches an 'against' pixel into the outline colour."""
        marks = []
        for y in range(self.h):
            for x in range(self.w):
                c = self.g[y][x]
                if c == "." or c == ch or (inside and c not in inside):
                    continue
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    if self.get(x + dx, y + dy) in against:
                        marks.append((x, y))
                        break
        for x, y in marks:
            self.set(x, y, ch)

    def mirror_from_left(self):
        for y in range(self.h):
            for x in range(self.w // 2):
                self.g[y][self.w - 1 - x] = self.g[y][x]

    def text(self):
        return "\n".join("".join(r) for r in self.g)


def sprite(name, c):
    return f"sprite {name} char\n{c.text()}\nend\n"


