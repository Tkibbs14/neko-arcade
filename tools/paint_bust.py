# ---------------------------------------------------------------- ears (shared, recoloured per character)


def ear_canvas(flat):
    c = Canvas()
    if not flat:
        outer = [(9, 3), (14, 24.5), (29, 16.5)]           # apex, outer base, inner base
        inner = [(12.5, 8.5), (16.5, 22), (25.5, 16.5)]
    else:
        outer = [(2, 13), (12, 27), (26, 17.5)]
        inner = [(6.5, 15.5), (13.5, 24.5), (22.5, 18)]
    c.poly(outer, "H")
    c.poly(inner, "p")
    # white fluff tufts growing out of the inner ear
    fx, fy = (inner[1][0] + inner[2][0]) / 2, (inner[1][1] + inner[2][1]) / 2
    for k, (dx, dy, n) in enumerate(((-3, -1, 4), (-1, -3, 5), (1, -2, 4), (-4, 1, 3))):
        for t in range(n):
            c.set(int(fx + dx - t * 0.6), int(fy + dy - t), "w")
            c.set(int(fx + dx - t * 0.6) + 1, int(fy + dy - t), "w")
    # light edge on the outer side, darker tip
    c.poly([outer[0], outer[1], (outer[1][0] + 1.5, outer[1][1] - 1.5), (outer[0][0] + 1.2, outer[0][1] + 2.5)], "h",
           only_over="H")
    ax, ay = outer[0]
    c.poly([(ax - 1, ay - 1), (ax + 4, ay + 5.5), (ax + 0.5, ay + 6.5)], "a", only_over="Hh")
    c.outline("k")
    c.mirror_from_left()
    return c


blocks.append(sprite("bust_ears_up", ear_canvas(False)))
